#!/usr/bin/env python3
"""Find a module's lines in a second tree, starting from its blocks in the first.

    python tools/dev/find_blocks.py --module vault --blocks docs/inventory/core_blocks.csv
        --from-repo <nms repo> --from-ref <ref> --from-prefix Release-NMS-Server
        --to-repo <eqemu repo> --to-base <ref> --to-head <ref>

For each file, prints the lines the module added in the first tree (--from-*, line ranges from core_blocks.csv) and
the matching added lines in the second tree (lines added between --to-base and --to-head with the same text), as
--file/--lines arguments for extract_patch.py. Lines with no match are listed so they can be checked by hand.
"""
import argparse, csv, difflib, subprocess, sys

# Shared lists that install generates; their module lines are not patched
GENERATED = ('zone/CMakeLists.txt', 'zone/command.cpp', 'zone/command.h', 'common/ruletypes.h',
             'common/database/database_update_manifest_custom.cpp')


def show(repo, ref, path):
    r = subprocess.run(['git', 'show', f'{ref}:{path}'], cwd=repo, capture_output=True)
    return r.stdout.decode('latin-1').splitlines() if r.returncode == 0 else None


def added(base, head):
    out = set()
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, base, head, autojunk=False).get_opcodes():
        if tag in ('insert', 'replace'):
            out.update(range(j1, j2))
    return out


def as_ranges(nums):
    out, nums = [], sorted(nums)
    for n in nums:
        if out and n == out[-1][1] + 1:
            out[-1][1] = n
        else:
            out.append([n, n])
    return ','.join(f'{a}-{b}' if a != b else str(a) for a, b in out)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--module', required=True)
    p.add_argument('--blocks', required=True)
    p.add_argument('--from-repo', required=True)
    p.add_argument('--from-ref', required=True)
    p.add_argument('--from-prefix', default='')
    p.add_argument('--to-repo', required=True)
    p.add_argument('--to-base', required=True)
    p.add_argument('--to-head', required=True)
    p.add_argument('--to-prefix', default='')
    a = p.parse_args()
    fp = a.from_prefix.strip('/') + '/' if a.from_prefix else ''
    tp = a.to_prefix.strip('/') + '/' if a.to_prefix else ''

    files = {}
    with open(a.blocks, encoding='utf-8') as fh:
        for row in csv.DictReader(fh):
            if row['module'] != a.module:
                continue
            f = row['file'].replace('Release-NMS-Server/', '')
            lo, _, hi = row['lines (at 0c897d30)'].partition('-')
            files.setdefault(f, set()).update(range(int(lo), int(hi or lo) + 1))

    for f in sorted(files):
        if f in GENERATED:
            print(f'# {f}: generated by install, skipped')
            continue
        src = show(a.from_repo, a.from_ref, fp + f)
        base, head = show(a.to_repo, a.to_base, tp + f), show(a.to_repo, a.to_head, tp + f)
        if src is None or base is None or head is None:
            print(f'# {f}: missing in one of the trees')
            continue
        new = added(base, head)
        want = [src[n - 1].strip() for n in sorted(files[f]) if n <= len(src)]
        found, missing, last = set(), [], -1
        for text in want:
            if not text:
                continue
            hits = [j for j in sorted(new) if head[j].strip() == text and j + 1 not in found]
            if not hits:
                missing.append(text)
                continue
            after = [j for j in hits if j > last]
            j = after[0] if after else hits[0]
            found.add(j + 1)
            last = j
        # Blank lines between matched lines of the same block go with them
        for n in sorted(found):
            k = n + 1
            while k <= len(head) and not head[k - 1].strip() and k - 1 in new:
                k += 1
            if k in found:
                found.update(range(n + 1, k))
        print(f'--file {f} --lines {as_ranges(found)}' if found else f'# {f}: nothing found')
        for m in missing:
            print(f'#   no match: {m[:110]}')


if __name__ == '__main__':
    main()
